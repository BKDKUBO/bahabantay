"""Deterministic MOCK provider. No network, no credentials.

Fake masks are derived from a hash of the image bytes so the same photo
always gives the same result (good for tests and demos).
"""
from __future__ import annotations
import hashlib
from .base import Mask, Segmentation
from .. import qa

BAND_TEXT = {
    "en": {"ankle": "ankle-deep", "knee": "knee-deep", "waist": "waist-deep", "chest": "chest-deep or higher", "none": "no flooding"},
    "fil": {"ankle": "hanggang bukung-bukong", "knee": "hanggang tuhod", "waist": "hanggang baywang", "chest": "hanggang dibdib o mas mataas", "none": "walang baha"},
}
PASS_TEXT = {
    "en": {"all": "passable to all vehicles", "trucks": "trucks only", "boats": "boats only"},
    "fil": {"all": "madadaanan ng lahat ng sasakyan", "trucks": "trak lang ang makakadaan", "boats": "bangka lang ang makakadaan"},
}


class MockVision:
    name = "mock"

    def segment(self, image: bytes, prompts: list[str]) -> Segmentation:
        h = hashlib.sha256(image).digest()
        masks: list[Mask] = []
        # reference object: pick one prompt deterministically
        refs = [p for p in prompts if p != "water"] or ["person"]
        ref = refs[h[0] % len(refs)]
        top, bottom = 0.30, 0.90               # reference object spans y 0.30..0.90
        if h[4] % 6 != 0:                      # ~1 in 6 photos: no reference object found
            masks.append(Mask(ref, (0.40, top, 0.60, bottom), 0.45 + (h[1] % 55) / 100))
        # waterline somewhere between bottom (no water) and top (fully submerged)
        frac = (h[2] % 101) / 100              # 0..1 of the object submerged
        waterline = bottom - frac * (bottom - top)
        if "water" in prompts and frac > 0.02:
            masks.append(Mask("water", (0.0, waterline, 1.0, 1.0), 0.75 + (h[3] % 25) / 100))
        return Segmentation(masks)

    def track_frames(self, frames, prompts):
        return [self.segment(f, prompts) for f in frames]


class MockAgent:
    """Deterministic agent: fixed tool order, no model."""
    name = "mock"

    def run(self, report: dict, tools) -> dict:
        trace = []
        nearby = tools.get_nearby_reports(report, radius_m=100); trace.append(("get_nearby_reports", len(nearby)))
        dup = tools.merge_duplicates(report, nearby); trace.append(("merge_duplicates", dup))
        risk = tools.flag_people_at_risk(report); trace.append(("flag_people_at_risk", risk))
        q = tools.ask_followup(report) if report["band"] == "cant_tell" else None
        trace.append(("ask_followup", q))
        return {"duplicate_of": dup, "people_at_risk": risk, "followup": q, "trace": trace}


class MockReports:
    name = "mock"

    def answer(self, summary: dict, question: str, lang: str) -> dict:
        return {**qa.answer(summary, question, lang), "provider": self.name}

    def situation_report(self, summary: dict, lang: str) -> str:
        lang = "fil" if lang == "fil" else "en"
        head = {"en": f"FLOOD SITUATION REPORT — Barangay {summary['barangay']} (SIMULATED/MOCK)",
                "fil": f"ULAT SA LAGAY NG BAHA — Barangay {summary['barangay']} (SIMULATED/MOCK)"}[lang]
        lines = [head, ""]
        for s in summary["streets"]:
            band = BAND_TEXT[lang][s["max_band"]]
            p = PASS_TEXT[lang][s["passability"]]
            if lang == "en":
                lines.append(f"- {s['street']}{(' ' + s['trend_arrow']) if s.get('trend_arrow') else ''}: {band} (~{s['latest_depth_cm']} cm), {p}. {s['reports']} report(s).")
            else:
                lines.append(f"- {s['street']}{(' ' + s['trend_arrow']) if s.get('trend_arrow') else ''}: {band} (~{s['latest_depth_cm']} cm), {p}. {s['reports']} ulat.")
            if s.get("trend") in ("rising", "falling"):
                t = s["trend"]; r = abs(s["rate_cm_per_h"])
                lines.append(f"  Trend: {t} ~{r} cm/hour." if lang == "en" else
                             f"  Takbo: {'tumataas' if t == 'rising' else 'bumababa'} ~{r} cm kada oras.")
            if s.get("people_at_risk"):
                lines.append("  ⚠ Possible people at risk reported." if lang == "en" else "  ⚠ May posibleng taong nangangailangan ng tulong.")
        if summary.get("needs_info"):
            n = summary["needs_info"]
            lines.append(f"- {n} report(s) waiting for reporter follow-up (depth unknown)." if lang == "en"
                         else f"- {n} ulat ang naghihintay ng sagot mula sa nag-ulat (hindi pa alam ang lalim).")
        lines.append("")
        lines.append("Generated by mock template, not by Muse Spark." if lang == "en"
                     else "Gawa ng mock template, hindi ng Muse Spark.")
        return "\n".join(lines)
